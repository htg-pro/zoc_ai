/**
 * Agent_Runtime bundler, pass 1 of 2 — zoc-agent-chat-rebuild R3.9, R4.3.
 *
 * esbuild collapses `src/main.ts` and its whole dependency graph into one
 * CommonJS file. Pass 2 (`@yao-pkg/pkg`, driven from `scripts/bundle_sidecar.py`)
 * turns that file into a self-contained executable per target triple.
 *
 * The output is asserted to contain no dynamic `require`. That check is the
 * point of this script existing rather than being one esbuild flag in a shell
 * command: `pkg` resolves `require` statically against a snapshot filesystem, so
 * a dynamic `require` surviving into the bundle produces a binary that is
 * missing a module and only says so at runtime, on a user's machine, in a code
 * path that may not run for weeks.
 */

import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, "..");
const OUT_FILE = resolve(PACKAGE_ROOT, "dist/agent-runtime.cjs");

/**
 * A `require(` call whose argument is not a string literal.
 *
 * Deliberately narrow: esbuild's own CJS interop emits `require("node:http")`
 * and similar literal calls, and those are exactly what `pkg` resolves fine. It
 * is the computed form — `require(name)`, `require(\`./${x}\`)` — that breaks the
 * snapshot, so that is what this matches.
 */
const DYNAMIC_REQUIRE = /\brequire\s*\(\s*(?!["'])/g;

async function main() {
  await mkdir(dirname(OUT_FILE), { recursive: true });

  const result = await build({
    entryPoints: [resolve(PACKAGE_ROOT, "src/bin.ts")],
    outfile: OUT_FILE,
    bundle: true,
    platform: "node",
    target: "node20",
    format: "cjs",
    // Node builtins stay external; everything else is inlined so the snapshot
    // filesystem has a single file to resolve.
    packages: "bundle",
    external: [],
    sourcemap: false,
    minify: false,
    legalComments: "none",
    logLevel: "info",
    metafile: true,
    define: { "process.env.NODE_ENV": '"production"' },
    banner: {
      js: "// Zoc AI Agent_Runtime — generated by scripts/bundle.mjs. Do not edit.",
    },
  });

  const code = await readFile(OUT_FILE, "utf8");
  const offenders = [...code.matchAll(DYNAMIC_REQUIRE)];
  if (offenders.length > 0) {
    const lines = offenders.slice(0, 5).map((match) => {
      const upto = code.slice(0, match.index ?? 0);
      const line = upto.split("\n").length;
      return `  dist/agent-runtime.cjs:${line}`;
    });
    throw new Error(
      `The bundle contains ${offenders.length} dynamic require call(s) (R4.3).\n` +
        `pkg resolves require statically, so each one is a module silently missing\n` +
        `from the packaged binary. First offenders:\n${lines.join("\n")}`,
    );
  }

  const bytes = Buffer.byteLength(code);
  await writeFile(
    resolve(PACKAGE_ROOT, "dist/bundle-meta.json"),
    JSON.stringify(
      {
        outFile: "dist/agent-runtime.cjs",
        bytes,
        inputs: Object.keys(result.metafile?.inputs ?? {}).length,
      },
      null,
      2,
    ),
  );

  process.stdout.write(
    `==> agent-runtime bundled: ${(bytes / 1024).toFixed(0)} kB, ` +
      `${Object.keys(result.metafile?.inputs ?? {}).length} inputs, no dynamic require\n`,
  );
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
